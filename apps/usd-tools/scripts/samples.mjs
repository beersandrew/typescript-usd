const samples = [
  { name: 'heath', title: "The witches' heath (Macbeth 1.1)", dir: 'browser', files: ['heath.usda'], root: 'heath.usda', ...STAGEHAND },
  { name: 'variants', title: 'Museum: variants', dir: 'composition/arcs/variants', root: 'variants.usda', ...MUSEUM },
  { name: 'cycles', title: 'Museum: composition errors', dir: 'composition/errors/cycles', root: 'cycles.usda', ...MUSEUM },
  { name: 'formats', title: 'Museum: file formats', dir: 'foundations/files/formats', root: 'formats.usda', ...MUSEUM },
  { name: 'packages', title: 'Museum: packages', dir: 'foundations/packages/packages', root: 'packages.usda', ...MUSEUM },
]

function walk(dir) {
  return readdirSync(dir).flatMap(name => {
    const path = join(dir, name)
    return statSync(path).isDirectory() ? walk(path) : [path]
  })
}

rmSync(out, { recursive: true, force: true })
mkdirSync(out, { recursive: true })
const files = []
for (const sample of samples) {
  const from = join(sample.base, sample.dir), to = join(out, sample.name)
  if (sample.files) {
    mkdirSync(to, { recursive: true })
    for (const file of sample.files) cpSync(join(from, file), join(to, file))
  } else {
    cpSync(from, to, { recursive: true, filter: src => !src.endsWith('.DS_Store') })
  }
  for (const file of walk(to)) files.push(relative(out, file))
}
cpSync(join(museum, 'LICENSE'), join(out, 'LICENSE-usd-museum.txt'))
