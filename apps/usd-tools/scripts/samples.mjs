// Copies the sample USD files the tool pages offer into public/samples and
// writes public/samples/manifest.json: each sample's name, root layer and
// source, and every file the pages may resolve.
//
//   node scripts/samples.mjs [--museum <usd-museum checkout>]
import { cpSync, mkdirSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'
import { homedir } from 'node:os'
import { execFileSync } from 'node:child_process'

const args = process.argv.slice(2)
const museum = args.includes('--museum') ? args[args.indexOf('--museum') + 1] : join(homedir(), 'git/usd-museum')
const out = new URL('../public/samples/', import.meta.url).pathname

