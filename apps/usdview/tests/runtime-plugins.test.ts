// Runtime plugins served by the viewer (Node, not a browser test): the .demo
// file format plugin and the generated DemoAnnotationAPI schema plugin are
// registered from their plugInfo URLs exactly as ?plugin= does.
import { readFile } from 'node:fs/promises'
import { describe, expect, it } from 'vitest'
import { Registry as PlugRegistry } from 'typescript-usd/plug'
import { Stage } from 'typescript-usd/usd'
import { createHttpResolverContext } from '../src/http-resolver'
import { propertyRows } from '../src/property-view'

const site = 'https://viewer.example/'
const publicDir = new URL('../public/', import.meta.url)
const local = (input: string | URL | Request) => new URL(new URL(String(input instanceof Request ? input.url : input)).pathname.slice(1), publicDir)
const serve = (async (input: string | URL | Request) => {
  try { return new Response(await readFile(local(input))) } catch { return new Response(null, { status: 404 }) }
}) as typeof fetch
const registry = PlugRegistry.GetInstance()
const imported: string[] = []
// Browsers import the module URL; Node reads the same file from public/.
registry._moduleImporter = url => { imported.push(url); return import(/* @vite-ignore */ local(url).href) }
const open = (path: string) => Stage.open(site + path, { resolverContext: createHttpResolverContext(site + path, undefined, serve) }).then(value => value!)

describe('runtime plugins served by the viewer', () => {
  it('opens a .demo layer through the file format plugin imported on first use', async () => {
    await registry.registerPluginsAsync(site + 'plugins/demo-file-format/plugInfo.json', { fetch: serve })
    expect(imported).toEqual([])
    const stage = await open('plugins/demo-file-format/scene.demo')
    try {
      expect(imported).toEqual([site + 'plugins/demo-file-format/demoFileFormat.js'])
      expect(stage.getPrim('/World/ball')?.typeName).toBe('Sphere')
      expect(stage.getPrim('/World/ball')?.getAttr('radius')?.getValue()).toBe(2)
      expect(stage.getPrim('/World/box')?.typeName).toBe('Cube')
    } finally { stage.dispose() }
  })

  it('shows DemoAnnotationAPI properties, authored and fallback, in the property view', async () => {
    await registry.registerPluginsAsync(site + 'plugins/demo-schema/plugInfo.json', { fetch: serve })
    const stage = await open('plugins/demo-schema/annotated.usda')
    try {
      const rows = (path: string) => Object.fromEntries(propertyRows(stage, path, 0)
        .filter(row => row.name.startsWith('annotation:')).map(row => [row.name, [row.typeName, row.value, row.source]]))
      expect(stage.getPrim('/World/Ball')!.hasAPI('DemoAnnotationAPI')).toBe(true)
      expect(rows('/World/Ball')).toEqual({
        'annotation:color': ['color3f', '(0.2, 0.6, 1)', 'default'],
        'annotation:text': ['string', 'One schema.usda, generated by both ports', 'default'],
      })
      expect(rows('/World/Box')).toEqual({
        'annotation:color': ['color3f', '(1, 0.8, 0)', 'fallback'],
        'annotation:text': ['string', '', 'fallback'],
      })
    } finally { stage.dispose() }
  })

  // That the served plugin is what usdGenSchema generates from
  // scripts/demo-schema.usda (scripts/generate-demo-schema.mjs --check) needs
  // OpenUSD's own usd/schema.usda for the schema's sublayer, so it is checked
  // with the capture tooling kept outside this repository (FIXTURES.md), not here.
})
