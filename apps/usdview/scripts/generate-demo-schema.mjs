// Generates the DemoAnnotationAPI schema plugin served at public/plugins/demo-schema/
// from scripts/demo-schema.usda, using typescript-usd's
// usdGenSchema (port of pxr/usd/usd/usdGenSchema.py).
//
//   pnpm exec vite-node scripts/generate-demo-schema.mjs [schema.usda] [--check]
//
// (vite-node because the workspace library is consumed as TypeScript source.)
//
// usdGenSchema resolves the schema's @usd/schema.usda@ sublayer from the
// OpenUSD source tree (OPENUSD_SOURCE, default: an OpenUSD-26.11.1 checkout beside the repository), as
// upstream resolves it from the installed usd plugin's resources.
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { usdGenSchema } from 'typescript-usd/usd'

const viewer = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const args = process.argv.slice(2)
const check = args.includes('--check')
const schemaPath = path.resolve(args.find(a => !a.startsWith('--')) ?? path.join(viewer, 'scripts/demo-schema.usda'))
const openusd = process.env.OPENUSD_SOURCE ?? path.resolve(viewer, '../../../OpenUSD-26.11.1')
const outDir = path.join(viewer, 'public/plugins/demo-schema')

const schemaText = await readFile(schemaPath, 'utf8')
const result = await usdGenSchema(schemaText, {
  resolveAsset: asset => readFile(path.join(openusd, 'pxr/usd', asset), 'utf8'),
})
const plugin = result.plugInfo.Plugins[0]
// The TypeScript usdGenSchema generates the registry artifacts but no schema
// classes, so there is no library for LibraryPath to name: the plugin is
// served as resources, the role upstream's codeless "resource" type plays.
// Root and ResourcePath are the plugin directory, as upstream installs them.
const plugInfo = { Plugins: [{ ...plugin, Type: 'resource', Root: '.', ResourcePath: '.', LibraryPath: undefined }] }
const header = [
  '# Generated by scripts/generate-demo-schema.mjs with typescript-usd usdGenSchema',
  `# from the demo schema.usda. Do not edit.`,
].join('\n')
const files = {
  'plugInfo.json': `${header}\n${JSON.stringify(plugInfo, null, 4)}\n`,
  'generatedSchema.usda': result.generatedSchemaUsda,
  // The source schema is served beside its generated files.
  'schema.usda': schemaText,
}
if (check) {
  const stale = []
  for (const [name, text] of Object.entries(files)) {
    const current = await readFile(path.join(outDir, name), 'utf8').catch(() => '')
    if (current !== text) stale.push(name)
  }
  if (stale.length) { console.error(`Stale demo schema plugin files: ${stale.join(', ')}`); process.exit(1) }
  console.log('Demo schema plugin is up to date.')
} else {
  await mkdir(outDir, { recursive: true })
  for (const [name, text] of Object.entries(files)) await writeFile(path.join(outDir, name), text)
  console.log(`Wrote ${Object.keys(files).join(', ')} to ${path.relative(viewer, outDir)}`)
}
