// Generates src/generated/files.ts: the MaterialX v1.39.5 data libraries
// (upstream libraries/) that the OpenUSD 26.11.1 reference build installs
// for UsdMtlxSearchPaths(). Every .mtlx document is included (MaterialX's
// loadLibraries reads all of them, implementation documents of every target
// included), plus the genglsl shader sources the GLSL shader generators
// resolve. Other targets' shader sources (genmsl, genosl, genmdl, genslang)
// are left out: nothing in this repository generates for them.
//
//   node scripts/generate.mjs [MaterialX checkout, default: MaterialX-1.39.5 beside the repository]

import { readdirSync, readFileSync, writeFileSync, mkdirSync, statSync } from 'node:fs'
import { join, relative, resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { execFileSync } from 'node:child_process'

const PIN = '7b64921ef1d42f2d57871e9d2c43dc11f041f26b' // tag v1.39.5
const source = resolve(process.argv[2] ?? resolve(dirname(fileURLToPath(import.meta.url)), '../../../../../MaterialX-1.39.5'))
const head = execFileSync('git', ['-C', source, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim()
if (head !== PIN) throw new Error(`Expected MaterialX ${PIN} (v1.39.5); found ${head}`)
const dirty = execFileSync('git', ['-C', source, 'status', '--porcelain', '--', 'libraries'], { encoding: 'utf8' })
if (dirty.trim()) throw new Error(`MaterialX checkout has local changes under libraries/:\n${dirty}`)

const root = join(source, 'libraries')
const files = []
function walk(dir) {
  for (const name of readdirSync(dir).sort()) {
    const path = join(dir, name)
    if (statSync(path).isDirectory()) { walk(path); continue }
    const rel = relative(root, path).split('\\').join('/')
    if (rel.endsWith('.mtlx') || /(^|\/)genglsl\/.*\.(glsl|inl|h)$/.test(rel)) files.push([rel, readFileSync(path, 'utf8')])
  }
}
walk(root)

const out = resolve(dirname(fileURLToPath(import.meta.url)), '../src/generated/files.ts')
mkdirSync(dirname(out), { recursive: true })
writeFileSync(out,
  `// MaterialX 1.39.5 data libraries (libraries/), embedded verbatim: each file\n` +
  `// keeps its upstream copyright notice. Copyright Contributors to the\n` +
  `// MaterialX Project. Apache License 2.0. stdlib/genglsl/lib/mx_noise.glsl and\n` +
  `// mx_hsv.glsl derive from Open Shading Language: Copyright (c) 2009-2010 Sony\n` +
  `// Pictures Imageworks Inc., et al. BSD 3-Clause License. See LICENSE and NOTICE.\n` +
  `\n` +
  `// MaterialX data libraries, v1.39.5 (${PIN}).\n` +
  `// Generated by scripts/generate.mjs. Do not edit.\n` +
  `export const MATERIALX_LIBRARY_FILES: ReadonlyArray<readonly [string, string]> = [\n` +
  files.map(([p, c]) => `  [${JSON.stringify(p)}, ${JSON.stringify(c)}],\n`).join('') + `]\n`)
console.log(`Generated ${out}: ${files.length} files, ${files.reduce((n, f) => n + f[1].length, 0)} bytes`)
