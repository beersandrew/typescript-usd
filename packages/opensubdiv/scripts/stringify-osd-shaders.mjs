// Generates src/osd/shaderSources.generated.ts from an OpenSubdiv 3.6.1
// checkout (tag v3_6_1): the shader files opensubdiv/osd/CMakeLists.txt:395
// stringifies into *.gen.h with tools/stringify/stringify.py, applied with
// the same rules (each line keeps its newline unless it ends in a line
// continuation backslash, which is dropped; a final "\n" is appended).
//
//   node scripts/stringify-osd-shaders.mjs <OpenSubdiv-3.6.1 checkout>
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const root = process.argv[2]
if (!root) {
  console.error('usage: node scripts/stringify-osd-shaders.mjs <OpenSubdiv checkout>')
  process.exit(1)
}
const files = {
  commonShaderSource: 'glslPatchCommon.glsl',
  commonTessShaderSource: 'glslPatchCommonTess.glsl',
  patchLegacyShaderSource: 'glslPatchLegacy.glsl',
  patchBasisTypesShaderSource: 'patchBasisTypes.h',
  patchBasisShaderSource: 'patchBasis.h',
  boxSplineTriangleShaderSource: 'glslPatchBoxSplineTriangle.glsl',
  bsplineShaderSource: 'glslPatchBSpline.glsl',
  gregoryShaderSource: 'glslPatchGregory.glsl',
  gregoryBasisShaderSource: 'glslPatchGregoryBasis.glsl',
  gregoryTriangleShaderSource: 'glslPatchGregoryTriangle.glsl',
}

// tools/stringify/stringify.py:30-54, as the text the generated C string
// literal denotes.
function stringify(text) {
  let out = ''
  const lines = text.split(/(?<=\n)/)
  for (const s of lines) {
    // stringify(s) iterates range(len(s)-1): the last character (the
    // newline) is dropped and "\n" re-added unless the line ends in "\".
    const body = s.slice(0, -1)
    if (body.endsWith('\\')) out += body.slice(0, -1)
    else out += body + '\n'
  }
  return out + '\n'
}

let ts = `// OpenSubdiv 3.6.1 opensubdiv/osd/ shader sources, embedded verbatim: each
// file keeps its upstream copyright notice. Modified Apache 2.0 License.
// See LICENSE-OpenSubdiv-3.6.1.txt and NOTICE.

// Generated by scripts/stringify-osd-shaders.mjs from OpenSubdiv 3.6.1
// (tag v3_6_1, commit f26d0ded) opensubdiv/osd/: the *.gen.h strings that
// opensubdiv/osd/CMakeLists.txt:395 builds with tools/stringify/stringify.py.
// Modified Apache 2.0 License (LICENSE-OpenSubdiv-3.6.1.txt). Do not edit.

`
for (const [name, file] of Object.entries(files)) {
  const text = readFileSync(path.join(root, 'opensubdiv/osd', file), 'utf8')
  ts += `/** opensubdiv/osd/${file} */\nexport const ${name}: string = ${JSON.stringify(stringify(text))}\n\n`
}
const here = path.dirname(new URL(import.meta.url).pathname)
writeFileSync(path.join(here, '../src/osd/shaderSources.generated.ts'), ts)
