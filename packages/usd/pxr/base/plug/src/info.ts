// plugInfo.json data model — the shape is upstream's VERBATIM
// (pxr/base/plug/info.cpp reads the same keys), so plugInfo.json files
// produced by usdGenSchema for C++ OpenUSD parse here unchanged. The path
// fields (Root/LibraryPath/ResourcePath) locate the plugin's ES module and
// resources when the document is registered with its URL
// (PlugRegistry.RegisterPluginsAsync, or RegisterPlugins with plugInfoUrl);
// otherwise resources are attached at registration and the fields are
// accepted and ignored.

/** Per-type entry in a plugin's Info.Types dict (plugin.cpp _DeclareType). */
export interface PlugInfoTypeEntry {
  /** Direct base type names (upstream: single-element for schemas). */
  bases?: string[]
  /** Alias table: base type name → alias registered under that base
   *  (for schemas: { UsdSchemaBase: '<usd type name>' }). */
  alias?: Record<string, string>
  schemaIdentifier?: string
  schemaKind?: string
  autoGenerated?: boolean
  apiSchemaAutoApplyTo?: string[]
  apiSchemaCanOnlyApplyTo?: string[]
  apiSchemaAllowedInstanceNames?: string[]
  /** Per-instance-name apply restrictions for multiple-apply schemas. */
  apiSchemaInstances?: Record<string, { apiSchemaCanOnlyApplyTo?: string[] }>
  [key: string]: unknown
}

/** One entry of the top-level Plugins array. */
export interface PlugInfoPlugin {
  Name: string
  /** 'library' for code-full plugins (LibraryPath names an ES module),
   *  'resource' for codeless ones. */
  Type: 'library' | 'resource' | string
  Info?: {
    Types?: Record<string, PlugInfoTypeEntry>
    AutoApplyAPISchemas?: Record<string, { apiSchemaAutoApplyTo?: string[] }>
    [key: string]: unknown
  }
  Root?: string
  LibraryPath?: string
  ResourcePath?: string
  [key: string]: unknown
}

/** The full plugInfo.json document. `Includes` are followed by
 *  RegisterPluginsAsync, except wildcards, which a URL space cannot list. */
export interface PlugInfo {
  Plugins?: PlugInfoPlugin[]
  [key: string]: unknown
}

/** A plugin resource: inline content (text, or the bytes of a binary
 *  resource such as an image), or an async loader (network/OPFS). */
export type PlugResourceLoader = () => Promise<string>
export type PlugResources = Record<string, string | Uint8Array | PlugResourceLoader>

// Ported from OpenUSD v26.08 pxr/base/plug/info.h:24-66. This is the parsed
// registration record consumed by PlugPlugin/PlugRegistry.
export class Plug_RegistrationMetadata {
  readonly type: string
  readonly name: string
  readonly pluginPath: string
  readonly resourcePath: string
  readonly plugInfo: PlugInfoPlugin

  constructor(plugInfo: PlugInfoPlugin) {
    this.type = plugInfo.Type
    this.name = plugInfo.Name
    this.pluginPath = plugInfo.LibraryPath ?? ''
    this.resourcePath = plugInfo.ResourcePath ?? ''
    this.plugInfo = plugInfo
  }
}
