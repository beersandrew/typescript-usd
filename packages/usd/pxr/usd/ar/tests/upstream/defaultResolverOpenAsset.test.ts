// resolver. ArFilesystemAsset::GetFileUnsafe has no analog without a FILE*,
// so its checks are not ported.

import { beforeAll, describe, expect, it } from 'vitest'
import { mkdtempSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import {
  FilesystemAsset as ArFilesystemAsset,
  GetResolver as ArGetResolver,
  ResolvedPath as ArResolvedPath,
  ResolverWriteMode as ArResolverWriteMode,
  SetPreferredResolver as ArSetPreferredResolver,
} from '../../src/index.ts'
import { _resetResolverForTest } from '../../src/internal.ts'

const decoder = new TextDecoder()

beforeAll(() => {
  _resetResolverForTest()
  ArSetPreferredResolver('ArDefaultResolver')
})

describe('testArDefaultResolver_CPP', () => {
  it('TestOpenAsset', async () => {
    const dir = mkdtempSync(join(tmpdir(), 'testArDefaultResolver_CPP'))
    try {
      const tmpPath = join(dir, 'asset')
      const contents = 'Test file generated by testArDefaultResolver_CPP'
      writeFileSync(tmpPath, contents)

      const asset = await ArGetResolver().openAsset(new ArResolvedPath(tmpPath))
      expect(asset).toBeDefined()
      expect(asset).toBeInstanceOf(ArFilesystemAsset)

      const assetSize = asset!.getSize()
      expect(assetSize).toBe(statSync(tmpPath).size)
      expect(assetSize).toBe(contents.length)

      expect(decoder.decode(await asset!.getBuffer())).toBe(contents)
      expect(decoder.decode(await asset!.read(assetSize, 0))).toBe(contents)
      expect(decoder.decode(await asset!.read(5, 10))).toBe(contents.slice(10, 15))
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })
})

describe('testArThreadedAssetCreation', () => {
  // Two assets opened for write "simultaneously" in a directory hierarchy
  // that does not exist yet must both be created.
  it('TestThreadedAssetCreation', async () => {
    const tmpDir = mkdtempSync(join(tmpdir(), 'TestCreateAsset'))
    try {
      const assetDir = join(tmpDir, 'a/b/c/d/e/f/g')
      const fullPath1 = join(assetDir, 'Asset1.out')
      const fullPath2 = join(assetDir, 'Asset2.out')
      const errors: string[] = []

      const createAsset = async (fullPath: string) => {
        const asset = await ArGetResolver().openAssetForWrite(
          new ArResolvedPath(fullPath), ArResolverWriteMode.Replace)
        if (asset) {
          await asset.write(new TextEncoder().encode(fullPath), 0)
          await asset.close()
        } else {
          errors.push(`Failed to open asset for write: ${fullPath}`)
        }
      }

      await Promise.all([createAsset(fullPath1), createAsset(fullPath2)])
      expect(errors).toEqual([])

      for (const fullPath of [fullPath1, fullPath2]) {
        const asset = await ArGetResolver().openAsset(new ArResolvedPath(fullPath))
        expect(asset, fullPath).toBeDefined()
        expect(asset!.getSize()).toBe(fullPath.length)
        expect(decoder.decode(await asset!.getBuffer())).toBe(fullPath)
      }
    } finally {
      rmSync(tmpDir, { recursive: true, force: true })
    }
  })
})
