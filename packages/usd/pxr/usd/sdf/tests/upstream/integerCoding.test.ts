describe('testSdfIntegerCoding', () => {
  it('round-trips 32-bit integers through Sdf_IntegerCompression', () => {
    expect(ints.length).toBe(1200)
    const compressed = encodeIntArrayCompressed(ints)
    expect(compressed.length).toBeLessThanOrEqual(intArrayCompressedBufSize(ints.length, 4))
    const decoded = decodeIntArray(
      lz4Decompress(compressed, intArrayCompressedBufSize(ints.length, 4)), ints.length, 4)
    // The values are uint32_t upstream; all fit in int32 here.
    expect(decoded).toEqual(ints)
  })

  it('round-trips 64-bit integers through Sdf_IntegerCompression64', () => {
    const ints64 = ints.map(x => BigInt(x) * BigInt(x))
    const compressed = encodeIntArray64Compressed(ints64)
    expect(compressed.length).toBeLessThanOrEqual(intArrayCompressedBufSize(ints64.length, 8))
    const decoded = decodeIntArray64(
      lz4Decompress(compressed, intArrayCompressedBufSize(ints64.length, 8)), ints64.length)
    expect(decoded.map(v => BigInt.asUintN(64, v))).toEqual(ints64)
  })
})
