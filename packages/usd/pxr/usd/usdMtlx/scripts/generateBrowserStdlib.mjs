// Generates the flattened MaterialX standard-library resource consumed by
// browser hosts. OpenUSD v26.08 UsdMtlxGetDocument("") similarly rolls the
// plugin's standard-library resources into one cached document.

import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { execFileSync } from 'node:child_process'
const source = process.env.MATERIALX_TS_SOURCE
if (!source) throw new Error('Set MATERIALX_TS_SOURCE to the MaterialX port checkout this stdlib is generated from')
const pin = '7ecc7803ee95e3b8a63c199e69da68d8fb6adcb4'
const revision = execFileSync('git', ['-C', source, 'rev-parse', 'HEAD'], {encoding:'utf8'}).trim()
if (revision !== pin) throw new Error(`Expected MaterialX source ${pin}; found ${revision}`)
const { getStandardLibraryDocument } = await import(pathToFileURL(resolve(source, 'packages/materialx/libraries/dist/index.js')).href)
import { writeToXmlString, XmlWriteOptions } from '@mtlx/format'

const options = new XmlWriteOptions()
options.writeXIncludeEnable = false

const xml = writeToXmlString(getStandardLibraryDocument(), options)
const output = resolve(
  dirname(fileURLToPath(import.meta.url)),
  '../src/generated/browserStdlibXml.ts',
)

mkdirSync(dirname(output), { recursive: true })
writeFileSync(
  output,
  `// MaterialX standard data libraries (libraries/), flattened; source revision ${pin}.\n// Copyright Contributors to the MaterialX Project. Apache License 2.0.\n// Some GLSL noise and colour files derive from Open Shading Language (BSD-3-Clause; see NOTICE).\n// See LICENSE and NOTICE.\n// Generated by scripts/generateBrowserStdlib.mjs. Do not edit.\nexport const BROWSER_STDLIB_XML = ${JSON.stringify(xml)}\n`,
)

console.log(`Generated ${output} (${xml.length} XML bytes)`)
