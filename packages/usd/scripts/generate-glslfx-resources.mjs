// Generate the TypeScript modules that embed each imaging library's vendored
// glslfx shader files, so HioGlslfx can read them synchronously as plugin
// resources (pxr/imaging/hio/src/glslfx.ts) in Node and in browser bundles
// without filesystem access at runtime.
//
//   node scripts/generate-glslfx-resources.mjs [--check]
//
// For every library below, pxr/imaging/<lib>/shaders/*.glslfx (and *.usda
// shader definitions; pxr/<path>/shaders for libraries named by path) is
// embedded verbatim in the library's src/shaders.generated.ts, keyed by the
// resource name 'shaders/<file>' (the "ShaderResources" subdirectory of the
// library's plugInfo.json). Output is deterministic (files sorted by name),
// so running the generator twice changes nothing. --check exits nonzero when
// a generated module is stale.
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

// library -> exported constant name
const LIBRARIES = {
  hdSt: 'HdSt_ShaderResourceFiles',
  hdsi: 'Hdsi_ShaderResourceFiles',
  hdx: 'Hdx_ShaderResourceFiles',
  'usd/plugin/usdShaders': 'UsdShaders_ShaderResourceFiles',
  'usd/usdHydra': 'UsdHydra_ShaderResourceFiles',
  'usdImaging/usdSkelImaging': 'UsdSkelImaging_ShaderResourceFiles',
}

// Library directory under pxr/: imaging libraries by name, others by path.
const libDir = (lib) => lib.includes('/') ? lib : path.join('imaging', lib)

export function generate(lib, exportName) {
  const dir = path.join(root, 'pxr', libDir(lib), 'shaders')
  const files = readdirSync(dir).filter((f) => f.endsWith('.glslfx') || f.endsWith('.usda')).sort()
  const lines = [
    `// OpenUSD 26.11.1 pxr/${libDir(lib)}/shaders/, embedded verbatim: each file`,
    `// keeps its upstream copyright notice. Tomorrow Open Source Technology`,
    `// License 1.0. See LICENSE and NOTICE.`,
    ``,
    `// GENERATED by scripts/generate-glslfx-resources.mjs from`,
    `// pxr/${libDir(lib)}/shaders/*.glslfx (verbatim OpenUSD 26.11.1 resources;`,
    `// see pxr/${libDir(lib)}/shaders/PROVENANCE.md). Do not edit by hand.`,
    ``,
    `/** Shader resource name ('shaders/<file>') -> file contents. */`,
    `export const ${exportName}: Readonly<Record<string, string>> = {`,
  ]
  for (const file of files) {
    const text = readFileSync(path.join(dir, file), 'utf8')
    lines.push(`  ${JSON.stringify(`shaders/${file}`)}: ${JSON.stringify(text)},`)
  }
  lines.push('}', '')
  return {
    output: path.join(root, 'pxr', libDir(lib), 'src', 'shaders.generated.ts'),
    text: lines.join('\n'),
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check')
  let stale = 0
  for (const [lib, exportName] of Object.entries(LIBRARIES)) {
    const { output, text } = generate(lib, exportName)
    const current = existsSync(output) ? readFileSync(output, 'utf8') : null
    if (current === text) continue
    stale++
    if (check) {
      console.error(`stale: ${path.relative(root, output)}`)
    } else {
      writeFileSync(output, text)
      console.log(`wrote ${path.relative(root, output)}`)
    }
  }
  if (check && stale) process.exit(1)
}
