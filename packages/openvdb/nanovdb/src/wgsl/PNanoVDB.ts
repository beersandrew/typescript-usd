// WGSL port of the PNanoVDB.h float-grid read subset (upstream's
// GPU-portable NanoVDB header): grid sampling (nearest + trilinear) and
// HDDA ray traversal with ZeroCrossing, over a NanoVDB grid buffer bound
// as a read-only storage buffer of u32 words.
//
// All struct offsets are injected from the same layout constants the CPU
// reader uses (testdata/fixtures/layout.json pins them to upstream
// sizeof/offsetof), so the WGSL cannot drift from the verified layout.
//
// DIVERGENCE from upstream PNanoVDB.h: 64-bit fields (tree node offsets,
// internal child offsets, root tile keys) are handled as u32 pairs; node
// byte offsets use only the low word, which holds for any grid < 4 GiB —
// far beyond practical WebGPU buffer limits. Times and positions are f32
// (GPU-native); bit-exactness with the CPU/C++ double path is not a goal
// here — visual parity is established by golden images.

import { FLOAT_LAYOUT, GRID_DATA_SIZE, TREE_DATA_SIZE } from '../NanoVDB.ts'

export interface PNanoVDBWGSLOptions {
  /** @group index for the grid buffer binding (default 0) */
  group?: number
  /** @binding index for the grid buffer binding (default 0) */
  binding?: number
  /** name of the storage buffer variable (default 'pnanovdb_buf') */
  bufferName?: string
}

/**
 * Returns the WGSL module source providing, for a float grid at byte
 * offset 0 of the bound buffer:
 *   pnanovdb_read_float(byteOffset)            -> f32
 *   pnanovdb_root_background()                 -> f32
 *   pnanovdb_root_bbox_min/max()               -> vec3<i32>
 *   pnanovdb_get_value(ijk: vec3<i32>)         -> f32   (tree traversal)
 *   pnanovdb_get_dim(ijk: vec3<i32>)           -> u32   (HDDA node dim)
 *   pnanovdb_sample_trilinear(xyz: vec3<f32>)  -> f32
 *   pnanovdb_hdda_* / pnanovdb_zero_crossing   (level-set ray intersection)
 */
export function pnanovdbWGSL(options: PNanoVDBWGSLOptions = {}): string {
  const group = options.group ?? 0
  const binding = options.binding ?? 0
  const buf = options.bufferName ?? 'pnanovdb_buf'
  const L = FLOAT_LAYOUT
  const TREE = GRID_DATA_SIZE // tree follows GridData
  return /* wgsl */ `
// generated by @vdb/nanovdb pnanovdbWGSL() — NanoVDB 32.9.1 float grid reader

@group(${group}) @binding(${binding}) var<storage, read> ${buf}: array<u32>;

fn pnanovdb_read_u32(byteOffset: u32) -> u32 {
  return ${buf}[byteOffset >> 2u];
}

fn pnanovdb_read_i32(byteOffset: u32) -> i32 {
  return bitcast<i32>(${buf}[byteOffset >> 2u]);
}

fn pnanovdb_read_float(byteOffset: u32) -> f32 {
  return bitcast<f32>(${buf}[byteOffset >> 2u]);
}

// low word of a little-endian i64 byte offset (grids < 4 GiB)
fn pnanovdb_read_offset(byteOffset: u32) -> u32 {
  return ${buf}[byteOffset >> 2u];
}

fn pnanovdb_read_coord(byteOffset: u32) -> vec3<i32> {
  return vec3<i32>(
    pnanovdb_read_i32(byteOffset),
    pnanovdb_read_i32(byteOffset + 4u),
    pnanovdb_read_i32(byteOffset + 8u));
}

// ---- tree/root entry points (grid at byte offset 0) ----

fn pnanovdb_root_offset() -> u32 {
  return ${TREE}u + pnanovdb_read_offset(${TREE}u + 24u); // TreeData.mNodeOffset[3]
}

fn pnanovdb_root_bbox_min() -> vec3<i32> {
  return pnanovdb_read_coord(pnanovdb_root_offset());
}

fn pnanovdb_root_bbox_max() -> vec3<i32> {
  return pnanovdb_read_coord(pnanovdb_root_offset() + 12u);
}

fn pnanovdb_root_tile_count() -> u32 {
  return pnanovdb_read_u32(pnanovdb_root_offset() + 24u);
}

fn pnanovdb_root_background() -> f32 {
  return pnanovdb_read_float(pnanovdb_root_offset() + ${L.rootBackground}u);
}

// ---- coordinate math (5-4-3 tree) ----

fn pnanovdb_leaf_offset_n(ijk: vec3<i32>) -> u32 {
  return u32(((ijk.x & 7) << 6) | ((ijk.y & 7) << 3) | (ijk.z & 7));
}

fn pnanovdb_lower_offset_n(ijk: vec3<i32>) -> u32 {
  return u32((((ijk.x & 127) >> 3) << 8) | (((ijk.y & 127) >> 3) << 4) | ((ijk.z & 127) >> 3));
}

fn pnanovdb_upper_offset_n(ijk: vec3<i32>) -> u32 {
  return u32((((ijk.x & 4095) >> 7) << 10) | (((ijk.y & 4095) >> 7) << 5) | ((ijk.z & 4095) >> 7));
}

// root key (NANOVDB_USE_SINGLE_ROOT_KEY): (u32(c) >> 12) packed 21 bits
// each as x<<42 | y<<21 | z, handled as a (hi, lo) u32 pair
fn pnanovdb_coord_to_key(ijk: vec3<i32>) -> vec2<u32> {
  let x = u32(ijk.x) >> 12u;
  let y = u32(ijk.y) >> 12u;
  let z = u32(ijk.z) >> 12u;
  let lo = z | (y << 21u);
  let hi = (y >> 11u) | (x << 10u);
  return vec2<u32>(hi, lo);
}

fn pnanovdb_mask_is_on(maskByteOffset: u32, n: u32) -> bool {
  let word = pnanovdb_read_u32(maskByteOffset + ((n >> 5u) << 2u));
  return (word & (1u << (n & 31u))) != 0u;
}

// ---- value lookup: root linear scan, then upper -> lower -> leaf ----

struct PNanoVDBProbe {
  // byteOffset semantics: 0 = miss (background / root tile value in 'value')
  found: bool,
  value: f32,
  childOffset: u32, // absolute byte offset of the upper node when found
}

fn pnanovdb_root_probe(ijk: vec3<i32>) -> PNanoVDBProbe {
  let root = pnanovdb_root_offset();
  let key = pnanovdb_coord_to_key(ijk);
  let n = pnanovdb_root_tile_count();
  var tile = root + ${L.rootSize}u;
  for (var i = 0u; i < n; i = i + 1u) {
    let keyLo = pnanovdb_read_u32(tile + ${L.rootTileKey}u);
    let keyHi = pnanovdb_read_u32(tile + ${L.rootTileKey}u + 4u);
    if (keyLo == key.y && keyHi == key.x) {
      let childLo = pnanovdb_read_offset(tile + ${L.rootTileChild}u);
      let childHi = pnanovdb_read_u32(tile + ${L.rootTileChild}u + 4u);
      if (childLo == 0u && childHi == 0u) {
        return PNanoVDBProbe(false, pnanovdb_read_float(tile + ${L.rootTileValue}u), 0u);
      }
      return PNanoVDBProbe(true, 0.0, root + childLo);
    }
    tile = tile + ${L.rootTileSize}u;
  }
  return PNanoVDBProbe(false, pnanovdb_root_background(), 0u);
}

fn pnanovdb_get_value(ijk: vec3<i32>) -> f32 {
  let probe = pnanovdb_root_probe(ijk);
  if (!probe.found) {
    return probe.value;
  }
  let upper = probe.childOffset;
  let un = pnanovdb_upper_offset_n(ijk);
  if (!pnanovdb_mask_is_on(upper + ${L.upperChildMask}u, un)) {
    return pnanovdb_read_float(upper + ${L.upperTable}u + un * ${L.upperTileSize}u);
  }
  let lower = upper + pnanovdb_read_offset(upper + ${L.upperTable}u + un * ${L.upperTileSize}u);
  let ln = pnanovdb_lower_offset_n(ijk);
  if (!pnanovdb_mask_is_on(lower + ${L.lowerChildMask}u, ln)) {
    return pnanovdb_read_float(lower + ${L.lowerTable}u + ln * ${L.lowerTileSize}u);
  }
  let leaf = lower + pnanovdb_read_offset(lower + ${L.lowerTable}u + ln * ${L.lowerTileSize}u);
  return pnanovdb_read_float(leaf + ${L.leafValues}u + pnanovdb_leaf_offset_n(ijk) * 4u);
}

fn pnanovdb_is_active(ijk: vec3<i32>) -> bool {
  let probe = pnanovdb_root_probe(ijk);
  if (!probe.found) {
    return false; // background or value tile (tile state not consulted on GPU hot path)
  }
  let upper = probe.childOffset;
  let un = pnanovdb_upper_offset_n(ijk);
  if (!pnanovdb_mask_is_on(upper + ${L.upperChildMask}u, un)) {
    return pnanovdb_mask_is_on(upper + ${L.upperValueMask}u, un);
  }
  let lower = upper + pnanovdb_read_offset(upper + ${L.upperTable}u + un * ${L.upperTileSize}u);
  let ln = pnanovdb_lower_offset_n(ijk);
  if (!pnanovdb_mask_is_on(lower + ${L.lowerChildMask}u, ln)) {
    return pnanovdb_mask_is_on(lower + ${L.lowerValueMask}u, ln);
  }
  let leaf = lower + pnanovdb_read_offset(lower + ${L.lowerTable}u + ln * ${L.lowerTileSize}u);
  return pnanovdb_mask_is_on(leaf + ${L.leafValueMask}u, pnanovdb_leaf_offset_n(ijk));
}

// node dim containing ijk (upstream ReadAccessor::getDim, for the HDDA)
fn pnanovdb_get_dim(ijk: vec3<i32>) -> u32 {
  let probe = pnanovdb_root_probe(ijk);
  if (!probe.found) {
    return 4096u;
  }
  let upper = probe.childOffset;
  if ((pnanovdb_read_u32(upper + 24u) & 1u) != 0u) { // mFlags skip bit
    return 4096u;
  }
  let un = pnanovdb_upper_offset_n(ijk);
  if (!pnanovdb_mask_is_on(upper + ${L.upperChildMask}u, un)) {
    return 128u;
  }
  let lower = upper + pnanovdb_read_offset(upper + ${L.upperTable}u + un * ${L.upperTileSize}u);
  if ((pnanovdb_read_u32(lower + 24u) & 1u) != 0u) {
    return 128u;
  }
  let ln = pnanovdb_lower_offset_n(ijk);
  if (!pnanovdb_mask_is_on(lower + ${L.lowerChildMask}u, ln)) {
    return 8u;
  }
  let leaf = lower + pnanovdb_read_offset(lower + ${L.lowerTable}u + ln * ${L.lowerTileSize}u);
  if (((pnanovdb_read_u32(leaf + ${L.leafFlags - 3}u) >> 24u) & 1u) != 0u) { // mFlags byte (offset ${L.leafFlags})
    return 8u;
  }
  return 1u;
}

// ---- sampling ----

fn pnanovdb_sample_nearest(xyz: vec3<f32>) -> f32 {
  return pnanovdb_get_value(vec3<i32>(round(xyz)));
}

fn pnanovdb_sample_trilinear(xyz: vec3<f32>) -> f32 {
  let flr = floor(xyz);
  let ijk = vec3<i32>(flr);
  let uvw = xyz - flr;
  let v000 = pnanovdb_get_value(ijk);
  let v001 = pnanovdb_get_value(ijk + vec3<i32>(0, 0, 1));
  let v010 = pnanovdb_get_value(ijk + vec3<i32>(0, 1, 0));
  let v011 = pnanovdb_get_value(ijk + vec3<i32>(0, 1, 1));
  let v100 = pnanovdb_get_value(ijk + vec3<i32>(1, 0, 0));
  let v101 = pnanovdb_get_value(ijk + vec3<i32>(1, 0, 1));
  let v110 = pnanovdb_get_value(ijk + vec3<i32>(1, 1, 0));
  let v111 = pnanovdb_get_value(ijk + vec3<i32>(1, 1, 1));
  return mix(
    mix(mix(v000, v001, uvw.z), mix(v010, v011, uvw.z), uvw.y),
    mix(mix(v100, v101, uvw.z), mix(v110, v111, uvw.z), uvw.y),
    uvw.x);
}

// ---- index <-> world (Map doubles truncated to the f32 mirrors at 296) ----

fn pnanovdb_grid_world_to_index(xyz: vec3<f32>) -> vec3<f32> {
  let base = 296u; // GridData.mMap
  let inv = mat3x3<f32>(
    pnanovdb_read_float(base + 36u), pnanovdb_read_float(base + 48u), pnanovdb_read_float(base + 60u),
    pnanovdb_read_float(base + 40u), pnanovdb_read_float(base + 52u), pnanovdb_read_float(base + 64u),
    pnanovdb_read_float(base + 44u), pnanovdb_read_float(base + 56u), pnanovdb_read_float(base + 68u));
  let vec = vec3<f32>(
    pnanovdb_read_float(base + 72u), pnanovdb_read_float(base + 76u), pnanovdb_read_float(base + 80u));
  return inv * (xyz - vec);
}

fn pnanovdb_grid_index_to_world(xyz: vec3<f32>) -> vec3<f32> {
  let base = 296u; // GridData.mMap: mMatF row-major
  let mat = mat3x3<f32>(
    pnanovdb_read_float(base + 0u), pnanovdb_read_float(base + 12u), pnanovdb_read_float(base + 24u),
    pnanovdb_read_float(base + 4u), pnanovdb_read_float(base + 16u), pnanovdb_read_float(base + 28u),
    pnanovdb_read_float(base + 8u), pnanovdb_read_float(base + 20u), pnanovdb_read_float(base + 32u));
  let vec = vec3<f32>(
    pnanovdb_read_float(base + 72u), pnanovdb_read_float(base + 76u), pnanovdb_read_float(base + 80u));
  return mat * xyz + vec;
}

// ---- HDDA (f32 times; port of math/HDDA.h incl. forward stepping) ----

struct PNanoVDBHDDA {
  dim: i32,
  t0: f32,
  t1: f32,
  voxel: vec3<i32>,
  stp: vec3<i32>,
  delta: vec3<f32>,
  next: vec3<f32>,
}

fn pnanovdb_hdda_init(eye: vec3<f32>, dir: vec3<f32>, t0: f32, t1: f32, dim: i32) -> PNanoVDBHDDA {
  var h: PNanoVDBHDDA;
  h.dim = dim;
  h.t0 = t0;
  h.t1 = t1;
  let pos = eye + dir * t0;
  let inv = 1.0 / dir;
  h.voxel = vec3<i32>(floor(pos)) & vec3<i32>(~(dim - 1));
  for (var axis = 0; axis < 3; axis = axis + 1) {
    if (dir[axis] == 0.0) {
      h.next[axis] = 3.402823e38; // disabled
      h.stp[axis] = 0;
    } else if (inv[axis] > 0.0) {
      h.stp[axis] = 1;
      h.next[axis] = t0 + (f32(h.voxel[axis] + dim) - pos[axis]) * inv[axis];
      h.delta[axis] = inv[axis];
    } else {
      h.stp[axis] = -1;
      h.next[axis] = t0 + (f32(h.voxel[axis]) - pos[axis]) * inv[axis];
      h.delta[axis] = -inv[axis];
    }
  }
  return h;
}

fn pnanovdb_hdda_min_axis(next: vec3<f32>) -> i32 {
  if (next.x < next.y && next.x < next.z) {
    return 0;
  }
  if (next.y < next.z) {
    return 1;
  }
  return 2;
}

fn pnanovdb_hdda_step(h: ptr<function, PNanoVDBHDDA>) -> bool {
  let axis = pnanovdb_hdda_min_axis((*h).next);
  // ENFORCE_FORWARD_STEPPING
  if ((*h).next[axis] <= (*h).t0) {
    (*h).next[axis] = (*h).next[axis] + ((*h).t0 - 0.999999 * (*h).next[axis] + 1.0e-6);
  }
  (*h).t0 = (*h).next[axis];
  (*h).next[axis] = (*h).next[axis] + f32((*h).dim) * (*h).delta[axis];
  (*h).voxel[axis] = (*h).voxel[axis] + (*h).dim * (*h).stp[axis];
  return (*h).t0 <= (*h).t1;
}

fn pnanovdb_hdda_update(h: ptr<function, PNanoVDBHDDA>, eye: vec3<f32>, dir: vec3<f32>, dim: i32) -> bool {
  if ((*h).dim == dim) {
    return false;
  }
  let voxelMax = ((*h).voxel + vec3<i32>((*h).dim - 1)) & vec3<i32>(~(dim - 1));
  let voxelMin = (*h).voxel & vec3<i32>(~(dim - 1));
  (*h).dim = dim;
  let pos = eye + dir * (*h).t0;
  let inv = 1.0 / dir;
  (*h).voxel = clamp(vec3<i32>(floor(pos)) & vec3<i32>(~(dim - 1)), voxelMin, voxelMax);
  for (var axis = 0; axis < 3; axis = axis + 1) {
    if ((*h).stp[axis] == 0) {
      continue;
    }
    (*h).next[axis] = (*h).t0 + (f32((*h).voxel[axis]) - pos[axis]) * inv[axis];
    if ((*h).stp[axis] > 0) {
      (*h).next[axis] = (*h).next[axis] + f32(dim) * inv[axis];
    }
  }
  return true;
}

// slab clip of an index-space ray against the root bbox; returns vec2(t0, t1)
// with t0 > t1 on miss
fn pnanovdb_ray_clip_root(eye: vec3<f32>, dir: vec3<f32>, t0in: f32, t1in: f32) -> vec2<f32> {
  let bmin = vec3<f32>(pnanovdb_root_bbox_min());
  let bmax = vec3<f32>(pnanovdb_root_bbox_max() + vec3<i32>(1));
  let inv = 1.0 / dir;
  let ta = (bmin - eye) * inv;
  let tb = (bmax - eye) * inv;
  let tmin = min(ta, tb);
  let tmax = max(ta, tb);
  let t0 = max(t0in, max(tmin.x, max(tmin.y, tmin.z)));
  let t1 = min(t1in, min(tmax.x, min(tmax.y, tmax.z)));
  return vec2<f32>(t0, t1);
}

struct PNanoVDBZeroCrossing {
  hit: bool,
  ijk: vec3<i32>,
  v: f32,
  t: f32,
}

// port of math::ZeroCrossing (level sets); ray is in INDEX space
fn pnanovdb_zero_crossing(eye: vec3<f32>, dir: vec3<f32>, t0in: f32, t1in: f32) -> PNanoVDBZeroCrossing {
  var out: PNanoVDBZeroCrossing;
  out.hit = false;
  let ts = pnanovdb_ray_clip_root(eye, dir, t0in, t1in);
  if (ts.x > ts.y || ts.y > 1e20) {
    return out;
  }
  var ijk = vec3<i32>(floor(eye + dir * ts.x));
  var h = pnanovdb_hdda_init(eye, dir, ts.x, ts.y, i32(pnanovdb_get_dim(ijk)));
  let v0 = pnanovdb_get_value(ijk);
  var steps = 0;
  loop {
    if (!pnanovdb_hdda_step(&h) || steps > 8192) {
      break;
    }
    steps = steps + 1;
    ijk = vec3<i32>(floor(eye + dir * (h.t0 + 1.0001)));
    pnanovdb_hdda_update(&h, eye, dir, i32(pnanovdb_get_dim(ijk)));
    if (h.dim > 1 || !pnanovdb_is_active(ijk)) {
      continue;
    }
    loop {
      if (!pnanovdb_hdda_step(&h) || steps > 8192) {
        break;
      }
      steps = steps + 1;
      if (!pnanovdb_is_active(h.voxel)) {
        break;
      }
      let v = pnanovdb_get_value(h.voxel);
      if (v * v0 < 0.0) {
        out.hit = true;
        out.ijk = h.voxel;
        out.v = v;
        out.t = h.t0;
        return out;
      }
    }
  }
  return out;
}
`
}

